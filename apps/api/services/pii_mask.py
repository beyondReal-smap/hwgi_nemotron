"""사용자 자유 입력 텍스트의 개인정보(PII)를 마스킹.

배경: sLLM 서버에 PII 필터가 있어 주민등록번호·카드번호 등이 포함된 입력을
HTTP 422(pii_blocked)로 차단한다. 약관·상품설명서를 그대로 복붙하면 예시 번호가
섞여 분석 전체가 실패할 수 있다.

대응: LLM 호출 직전에 PII를 마스킹한다. PII는 타겟 분석·소구점 추출에 무의미하므로
품질 영향이 없고, 동시에 PII를 LLM·로그·영속 저장소에 남기지 않아 보안상으로도 옳다.

마스킹 대상은 명확한 형식의 PII만 한정(오탐 최소화):
- 주민등록번호/외국인등록번호: YYMMDD-NNNNNNN
- 카드번호: 4-4-4-4 (구분자 일관)
- 휴대전화: 01X-XXXX-XXXX

보장 금액·날짜·증권번호 같은 일반 숫자는 위 형식과 겹치지 않아 보존된다.
"""

from __future__ import annotations

import re

# 주민등록번호/외국인등록번호: 6자리-7자리, 구분자는 하이픈 또는 공백 (필수 — 13자리 연속은
# 법인등록번호 등과 혼동되므로 제외해 오탐을 막는다)
_RRN = re.compile(r"\b\d{6}[-\s]\d{7}\b")

# 카드번호: 4-4-4-4(또는 마지막 3~4자리). 구분자(하이픈/공백)는 동일해야 매칭 — \1 역참조로 일관성 강제
_CARD = re.compile(r"\b\d{4}([-\s])\d{4}\1\d{4}\1\d{3,4}\b")

# 휴대전화: 010/011/016/017/018/019 - 3~4자리 - 4자리 (콜센터 1588 등 국번은 제외됨)
_PHONE = re.compile(r"\b01[0-9][-\s]?\d{3,4}[-\s]?\d{4}\b")

_RRN_MASK = "******-*******"
_CARD_MASK = "****-****-****-****"
_PHONE_MASK = "010-****-****"


def mask_pii(text: str) -> str:
    """입력 텍스트의 주민번호·카드번호·휴대전화를 마스킹한다.

    None/빈 문자열은 그대로 반환. 멱등(이미 마스킹된 ****는 다시 매칭되지 않음).
    """
    if not text:
        return text
    text = _RRN.sub(_RRN_MASK, text)
    text = _CARD.sub(_CARD_MASK, text)
    text = _PHONE.sub(_PHONE_MASK, text)
    return text
